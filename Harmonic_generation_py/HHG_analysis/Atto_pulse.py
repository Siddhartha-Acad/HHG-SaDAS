print(f" {WHITE}~~~~~~~~~~~~: Conversion efficiency :~~~~~~~~~~~~{RESET}")
print(f" Total laser energy (∫E² dt)      : {laser_energy:.6e}")
print(f" Total harmonic energy (∫P(ω) dω) : {harmonic_energy:.6e}")
print(f" Conversion efficiency (eta)      : {eta:.6e}")



# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
#              Attosecond pulse via spectral gating                  |
# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
accel_FFT = -(freq_w**2) * dipole_mom_FFT   # Dipole acceleration spectrum (physically radiated quantity)
harmonic_orders_full = freq_w / w0          # Harmonic order axis (signed, +/- branches)

# Initial gate / GUI default values
harm_min_0, harm_max_0 = 15.0, 45.0
gate_order_0 = 20
t_min_T, t_max_T = float(t.min()/T), float(t.max()/T)
zoom_min_0, zoom_max_0 = t_min_T, t_max_T
gauss_pos_0    = (t_min_T + t_max_T) / 2
gauss_width_0  = 0.05
gauss_height_0 = 1.0

# Soft-edged window (super-Gaussian) instead of a hard cutoff,
# to avoid ringing artifacts from an abrupt spectral edge.
# Evaluated on |freq_w|/w0 so it's symmetric for +/- frequencies,
# which keeps a_t_gated real after the inverse FFT.
def soft_gate(mask_freqs, lo, hi, order=6):
    center = (lo + hi) / 2
    width  = (hi - lo) / 2
    return np.exp(-((np.abs(mask_freqs) - center) / width)**order)

def compute_pulse(lo, hi, order):
    """Recompute gate + gated acceleration spectrum + attosecond pulse for given (lo, hi, order)."""
    gate = soft_gate(harmonic_orders_full, lo, hi, order)
    accel_gated = accel_FFT * gate
    a_t_gated = ft.ifft(accel_gated)
    intensity = np.abs(a_t_gated)**2
    intensity /= intensity.max()
    return gate, intensity

gate, attosecond_intensity = compute_pulse(harm_min_0, harm_max_0, gate_order_0)
gate_pos = gate[positive_freq_mask]         # Gate values on the positive-frequency axis (for overlay on HHG spectrum)



